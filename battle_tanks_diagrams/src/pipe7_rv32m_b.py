from h import *

RED = "#c0392b"


def build():
    f = Fig(2000, 2300, "Fig P7b - RV32M (2/2): iterative divider (DIV / DIVU / REM / REMU), special cases and pipeline stall",
            "Radix-2 restoring divider on magnitudes: 32 clocks.  Signs are fixed before / after.  Divide-by-zero and overflow follow the RISC-V spec (no trap).")
    part_a(f)
    part_b(f)
    part_c(f)
    part_d(f)
    return f


def part_a(f):
    f.region(20, 90, 1960, 420, "PART A - input conditioning: absolute values and result-sign flags", RED)
    a = port(f, 40, 170, "alu_operand1[31:0]  (dividend)", 10, color="#3b5bdb")
    b = port(f, 40, 330, "alu_operand2[31:0]  (divisor)", 10, color="#3b5bdb")
    sg = port(f, 40, 450, "is_signed_div = ~funct3[0]", 10, color="#2e9d3a")
    ng1 = f.gate("and", 520, 130, 40, 36); ng2 = f.gate("and", 520, 290, 40, 36)
    a31 = port(f, 360, 130, "A[31]", 9, w=46); b31 = port(f, 360, 290, "B[31]", 9, w=46)
    sgp1 = port(f, 360, 170, "is_signed", 9, w=60, color="#2e9d3a"); sgp2 = port(f, 360, 330, "is_signed", 9, w=60, color="#2e9d3a")
    f.wire([a31["r"], (480, 130), (480, ng1["in1"][1]), ng1["in1"]]); f.wire([sgp1["r"], (490, 170), (490, ng1["in2"][1]), ng1["in2"]], "ctrl")
    f.wire([b31["r"], (480, 290), (480, ng2["in1"][1]), ng2["in1"]]); f.wire([sgp2["r"], (490, 330), (490, ng2["in2"][1]), ng2["in2"]], "ctrl")
    na = port(f, 640, ng1["out"][1], "neg_a  (dividend negative)", 9, color="#2e9d3a"); nb = port(f, 640, ng2["out"][1], "neg_b  (divisor negative)", 9, color="#2e9d3a")
    f.wire([ng1["out"], na["l"]], "ctrl"); f.wire([ng2["out"], nb["l"]], "ctrl")
    ma = f.mux(1000, 130, 90, ins=("0", "1"), sel=None, w=40)
    pa = port(f, 880, ma["0"][1], "A", 9, w=24); pn = f.op(850, 190, "0 - A", w=110, h=36, ins=("a",), ts=11)
    f.wire([pa["r"], ma["0"]])
    f.wire([pn["y"], (990, pn["y"][1]), (990, ma["1"][1]), ma["1"]])
    pin_a = port(f, 740, pn["a"][1], "A", 9, w=24); f.wire([pin_a["r"], pn["a"]])
    sa = cport(f, ma["sel"][0], ma["sel"][1] + 50, "neg_a", 9, "#2e9d3a"); f.wire([sa["t"], ma["sel"]], "ctrl")
    oa = port(f, 1160, ma["out"][1], "abs_a[31:0]", 10, color=RED); f.wire([ma["out"], oa["l"]], bus="32")
    mb = f.mux(1000, 300, 90, ins=("0", "1"), sel=None, w=40)
    pb = port(f, 880, mb["0"][1], "B", 9, w=24); pm = f.op(850, 360, "0 - B", w=110, h=36, ins=("a",), ts=11)
    f.wire([pb["r"], mb["0"]]); f.wire([pm["y"], (990, pm["y"][1]), (990, mb["1"][1]), mb["1"]])
    pin_b = port(f, 740, pm["a"][1], "B", 9, w=24); f.wire([pin_b["r"], pm["a"]])
    sb = cport(f, mb["sel"][0], mb["sel"][1] + 50, "neg_b", 9, "#2e9d3a"); f.wire([sb["t"], mb["sel"]], "ctrl")
    ob = port(f, 1160, mb["out"][1], "abs_b[31:0]", 10, color=RED); f.wire([mb["out"], ob["l"]], bus="32")
    x = f.gate("xor", 1440, 160, 44, 36)
    xa = port(f, 1300, 150, "neg_a", 9, w=46, color="#2e9d3a"); xb = port(f, 1300, 200, "neg_b", 9, w=46, color="#2e9d3a")
    f.wire([xa["r"], (1410, 150), (1410, x["in1"][1]), x["in1"]], "ctrl"); f.wire([xb["r"], (1420, 200), (1420, x["in2"][1]), x["in2"]], "ctrl")
    qs = port(f, 1560, x["out"][1], "quot_neg = neg_a ^ neg_b", 10, color="#2e9d3a"); f.wire([x["out"], qs["l"]], "ctrl")
    rn = port(f, 1560, 260, "rem_neg = neg_a", 10, color="#2e9d3a")
    f.note(1300, 330, "Quotient is negative if the signs differ; the remainder takes the dividend's sign (RISC-V).", 10)
    f.note(1300, 350, "Unsigned DIVU / REMU: is_signed = 0, so neg_a = neg_b = 0 and nothing is negated.", 10)


def part_b(f):
    f.region(20, 540, 1960, 640, "PART B - the 32-clock restoring divider: remainder / quotient shift registers, subtract, restore, counter", RED)
    ab = port(f, 40, 620, "abs_a[31:0]  (load into quotient reg)", 10, color=RED)
    bb = port(f, 40, 1000, "abs_b[31:0]  (divisor reg, held)", 10, color=RED)
    st = port(f, 40, 700, "start", 10, color="#2e9d3a")
    # remainder register path
    sh = f.op(380, 760, "{ rem[30:0], quo[31] }", w=190, h=40, ins=("a",), ts=10)
    rem_q = port(f, 330, 860, "rem_q[31:0]", 10, color=RED)
    quo_q = port(f, 330, 910, "quo_q[31:0]", 10, color=RED)
    sub = f.op(660, 760, "trial - div", w=150, h=60, ins=("a", "b"), ts=11, showpins=True)
    f.wire([sh["y"], (620, sh["y"][1]), (620, sub["a"][1]), sub["a"]], bus="32")
    f.wire([bb["r"], (600, 1000), (600, sub["b"][1]), sub["b"]], bus="32")
    ge = port(f, 830, 830, "diff_ge_0 = no borrow", 9, color="#2e9d3a")
    f.wire([(810, 800), (820, 800), (820, 830), ge["l"]], "ctrl")
    rm = f.mux(1020, 740, 100, ins=("0 restore", "1 keep diff"), sel=None, w=50)
    f.wire([(810, 780), (950, 780), (950, rm["1 keep diff"][1]), rm["1 keep diff"]], bus="32")
    f.wire([sh["y"], (620, sh["y"][1]), (620, 700), (980, 700), (980, rm["0 restore"][1]), rm["0 restore"]], bus="32", label="trial (restore)", seg=2, ldy=-2)
    sp = cport(f, rm["sel"][0], rm["sel"][1] + 50, "diff_ge_0", 9, "#2e9d3a"); f.wire([sp["t"], rm["sel"]], "ctrl")
    ld = f.mux(1200, 740, 100, ins=("0", "1"), sel=None, w=50)
    f.wire([rm["out"], ld["1"]], bus="32")
    z = port(f, 1110, ld["0"][1], "0 (clear)", 9, w=70); f.wire([z["r"], ld["0"]])
    lp = cport(f, ld["sel"][0], ld["sel"][1] + 50, "busy", 9, "#2e9d3a"); f.wire([lp["t"], ld["sel"]], "ctrl")
    rf = f.seq(1380, 745, 160, 50, "rem_q[31:0]", ts=11); pin(f, rf, "D", "L", 25, show=False); pin(f, rf, "Q", "R", 25, show=False)
    f.wire([ld["out"], rf["D"]], bus="32")
    rq = (rf["Q"][0] + 40, rf["Q"][1]); f.wire([rf["Q"], rq], arrow=False); f.dot(rq)
    f.wire([rq, (rq[0], 860), (1000, 860)][:0] + [rq, (rq[0], 680), (360, 680), (360, sh["a"][1]), sh["a"]], bus="32", label="rem_q (feeds shift)", seg=1, ldy=-2)
    ro = port(f, 1660, rf["Q"][1], "remainder_abs[31:0]", 10, color=RED); f.wire([(rq[0], rq[1]), ro["l"]], bus="32")
    # quotient register
    qm = f.mux(1200, 940, 90, ins=("0", "1"), sel=None, w=50)
    qs = f.op(960, 960, "{ quo[30:0], diff_ge_0 }", w=200, h=36, ins=("a",), ts=10)
    qin = port(f, 760, qs["a"][1], "quo_q", 9, w=60); f.wire([qin["r"], qs["a"]])
    f.wire([qs["y"], (1180, qs["y"][1]), (1180, qm["1"][1]), qm["1"]], bus="32")
    ql = port(f, 1020, qm["0"][1], "abs_a  (start: load dividend)", 9, w=170, color=RED); f.wire([ql["r"], qm["0"]])
    qp = cport(f, qm["sel"][0], qm["sel"][1] + 50, "busy", 9, "#2e9d3a"); f.wire([qp["t"], qm["sel"]], "ctrl")
    qf = f.seq(1380, 945, 160, 50, "quo_q[31:0]", ts=11); pin(f, qf, "D", "L", 25, show=False); pin(f, qf, "Q", "R", 25, show=False)
    f.wire([qm["out"], qf["D"]], bus="32")
    qo = port(f, 1660, qf["Q"][1], "quotient_abs[31:0]", 10, color=RED); f.wire([qf["Q"], qo["l"]], bus="32")
    f.text(60, 1100, "Each clock while busy:  trial = { rem[30:0], quo[31] };  diff = trial - divisor;  if no borrow  rem <- diff,  quo <- { quo[30:0], 1 }  else  rem <- trial,  quo <- { quo[30:0], 0 }.", 10, anchor="start", color="#333")
    f.text(60, 1125, "(The mux inputs 'restore' / 'keep diff' implement the restoring step; start loads abs_a into the quotient register and clears the remainder.)", 10, anchor="start", color="#555")


def part_c(f):
    f.region(20, 1210, 1960, 360, "PART C - control: IDLE / BUSY state, 5-bit counter, stall", RED)
    ds = port(f, 40, 1290, "is_div_op = m_ext & funct3[2]", 10, color="#2e9d3a")
    dn = port(f, 40, 1420, "done", 10, color="#2e9d3a")
    n = f.gate("not", 300, 1406, 30, 28)
    f.wire([dn["r"], n["in"]], "ctrl")
    g = f.gate("and", 420, 1290, 40, 40)
    f.wire([ds["r"], (380, 1290), (380, g["in1"][1]), g["in1"]], "ctrl")
    f.wire([n["out"], (390, n["out"][1]), (390, g["in2"][1]), g["in2"]], "ctrl")
    sp = port(f, 540, g["out"][1], "pipeline_stall = is_div_op & ~done", 10, color=RED)
    f.wire([g["out"], sp["l"]], "ctrl")
    f.text(40, 1470, "pipeline_stall = 1 freezes IF/ID (PC hold, Fig P1) and inserts NOP bubbles toward WB until done = 1; the result is then written once.", 10, anchor="start", color="#555")
    cn = f.op(980, 1280, "cnt + 1", w=100, h=36, ins=("a",))
    cm = f.mux(1160, 1260, 90, ins=("0", "1"), sel=None, w=40)
    z = port(f, 1050, cm["0"][1], "5'd0", 9, w=40); f.wire([z["r"], cm["0"]])
    f.wire([cn["y"], (1120, cn["y"][1]), (1120, cm["1"][1]), cm["1"]], bus="5")
    cp = cport(f, cm["sel"][0], cm["sel"][1] + 50, "busy", 9, "#2e9d3a"); f.wire([cp["t"], cm["sel"]], "ctrl")
    cf = f.seq(1300, 1265, 150, 50, "cnt[4:0]", ts=11); pin(f, cf, "D", "L", 25, show=False); pin(f, cf, "Q", "R", 25, show=False)
    f.wire([cm["out"], cf["D"]], bus="5")
    tq = (cf["Q"][0] + 40, cf["Q"][1]); f.wire([cf["Q"], tq], arrow=False); f.dot(tq)
    f.wire([tq, (tq[0], 1360), (940, 1360), (940, cn["a"][1]), cn["a"]], label="cnt_q", seg=1, ldy=-2)
    c31 = f.op(1560, 1280, "cnt_q == 31", w=140, h=36, ins=("a",), ts=11)
    f.wire([(tq[0], tq[1]), c31["a"]])
    dd = port(f, 1760, c31["y"][1], "last_cycle", 10, color="#2e9d3a"); f.wire([c31["y"], dd["l"]], "ctrl")
    f.text(600, 1520, "busy: set by 'start' (first cycle of a DIV/REM in EX), cleared by last_cycle.  done = last_cycle (registered) or special-case bypass.", 10, anchor="start", color="#555")


def part_d(f):
    f.region(20, 1600, 1960, 680, "PART D - sign fix, divide-by-zero / overflow special cases, final selection", RED)
    q = port(f, 40, 1680, "quotient_abs[31:0]", 10, color=RED)
    r = port(f, 40, 1860, "remainder_abs[31:0]", 10, color=RED)
    qn = f.op(300, 1665, "0 - quo", w=110, h=36, ins=("a",), ts=11)
    rn = f.op(300, 1845, "0 - rem", w=110, h=36, ins=("a",), ts=11)
    f.wire([q["r"], (260, 1680), (260, qn["a"][1]), qn["a"]]); f.wire([r["r"], (260, 1860), (260, rn["a"][1]), rn["a"]])
    qm = f.mux(560, 1650, 100, ins=("0", "1"), sel=None, w=40); rm = f.mux(560, 1830, 100, ins=("0", "1"), sel=None, w=40)
    f.wire([(260, 1680), (260, 1665), (500, 1665), (500, qm["0"][1]), qm["0"]][:1] + [(260, 1680), (260, 1650), (520, 1650), (520, qm["0"][1]), qm["0"]])
    f.dot((260, 1680))
    f.wire([qn["y"], (470, qn["y"][1]), (470, qm["1"][1]), qm["1"]])
    f.wire([(260, 1860), (260, 1830), (520, 1830), (520, rm["0"][1]), rm["0"]]); f.dot((260, 1860))
    f.wire([rn["y"], (470, rn["y"][1]), (470, rm["1"][1]), rm["1"]])
    qs = cport(f, qm["sel"][0], qm["sel"][1] + 50, "quot_neg", 9, "#2e9d3a"); f.wire([qs["t"], qm["sel"]], "ctrl")
    rs = cport(f, rm["sel"][0], rm["sel"][1] + 50, "rem_neg", 9, "#2e9d3a"); f.wire([rs["t"], rm["sel"]], "ctrl")
    # special-case detectors
    bb = port(f, 40, 2030, "abs_b[31:0]", 9, color=RED)
    zc = f.op(200, 2010, "abs_b == 0", w=150, h=36, ins=("a",), ts=11)
    f.wire([bb["r"], zc["a"]])
    dz = port(f, 400, zc["y"][1], "div_by_zero", 9, color="#2e9d3a"); f.wire([zc["y"], dz["l"]], "ctrl")
    ov = f.op(200, 2080, "signed & A == INT_MIN & B == -1", w=280, h=36, ins=("a",), ts=10)
    ia = port(f, 40, 2098, "A, B, is_signed", 9, color="#3b5bdb"); f.wire([ia["r"], ov["a"]])
    ovp = port(f, 520, ov["y"][1], "overflow", 9, color="#2e9d3a"); f.wire([ov["y"], ovp["l"]], "ctrl")
    qs2 = f.mux(900, 1650, 150, ins=("0 normal", "1 B==0", "2 overflow"), sel=None, w=50)
    rs2 = f.mux(900, 1850, 150, ins=("0 normal", "1 B==0", "2 overflow"), sel=None, w=50)
    f.wire([qm["out"], (700, qm["out"][1]), (700, qs2["0 normal"][1]), qs2["0 normal"]], bus="32")
    f.wire([rm["out"], (700, rm["out"][1]), (700, rs2["0 normal"][1]), rs2["0 normal"]], bus="32")
    for m, (a, b) in ((qs2, ("32'hFFFF_FFFF", "32'h8000_0000")), (rs2, ("A  (dividend)", "32'h0000_0000"))):
        p1 = port(f, 760, m["1 B==0"][1], a, 9, w=130); f.wire([p1["r"], m["1 B==0"]])
        p2 = port(f, 760, m["2 overflow"][1], b, 9, w=130); f.wire([p2["r"], m["2 overflow"]])
    for m in (qs2, rs2):
        sp = cport(f, m["sel"][0], m["sel"][1] + 50, "{overflow, div_by_zero}", 9, "#2e9d3a"); f.wire([sp["t"], m["sel"]], "ctrl")
    # final: pick quotient vs remainder by funct3[1]
    fm = f.mux(1200, 1760, 100, ins=("0 DIV", "1 REM"), sel=None, w=50)
    f.wire([qs2["out"], (1130, qs2["out"][1]), (1130, fm["0 DIV"][1]), fm["0 DIV"]], bus="32")
    f.wire([rs2["out"], (1150, rs2["out"][1]), (1150, fm["1 REM"][1]), fm["1 REM"]], bus="32")
    fs = cport(f, fm["sel"][0], fm["sel"][1] + 50, "funct3[1]", 9, "#2e9d3a"); f.wire([fs["t"], fm["sel"]], "ctrl")
    do = port(f, 1380, fm["out"][1], "div_result[31:0]  -> Fig P7c result select", 11, color=RED)
    f.wire([fm["out"], do["l"]], bus="32")
    f.text(1000, 2010, "div_by_zero: DIV / DIVU -> all ones, REM / REMU -> the dividend.   overflow (signed INT_MIN / -1): DIV -> INT_MIN, REM -> 0.   No trap, as the RISC-V spec requires.", 10, anchor="start", color="#555")
    f.text(1000, 2040, "{overflow, div_by_zero} encodes the mux select: 00 normal, 01 divide by zero, 10 overflow.  DIV / DIVU use funct3[1]=0, REM / REMU use funct3[1]=1.", 10, anchor="start", color="#555")
    f.text(1000, 2070, "In the special cases the divider is bypassed: done is asserted at once, so there is no 32-clock wait.", 10, anchor="start", color="#555")
