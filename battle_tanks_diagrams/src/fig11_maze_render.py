from h import *


def cport(f, cx, y, text, size=9, color="#000"):
    w = tw(text, size)
    return port(f, cx - w / 2, y, text, size, color=color)


def build():
    f = Fig(2100, 1260, "Fig 11 - Maze Tile Renderer: pixel (x, y) -> tile address -> wall / floor colour",
            "24 px tiles, 20 x 20 = 480 x 480 playfield at the left of the 640 x 480 screen.  No divider: tile column / row are small counters that step in sync with x / y.")
    f.region(20, 90, 2060, 700, "PART A - tile counter cell  (instantiate 2x:  X axis and Y axis)", "#008a8a")
    f.note(1300, 640, "X axis:  step = pix_ce,     restart = h_end            (Fig 8)", 11)
    f.note(1300, 658, "Y axis:  step = line_tick,  restart = line_tick & v_end  (Fig 8)", 11)
    B = 300
    # ---- sub counter row
    op1 = f.op(300, 150, "sub_q + 1", w=110, h=36, ins=("a",))
    op2 = f.op(300, 200, "sub_q == 23", w=130, h=36, ins=("a",))
    W = f.mux(560, B, 80, ins=("0", "1"), sel=None, w=36)
    S = f.mux(680, B, 80, ins=("0", "1"), sel=None, w=36)
    R = f.mux(800, B, 80, ins=("0", "1"), sel=None, w=36)
    ff = f.seq(920, B + 15, 130, 50, "sub_q[4:0]", ts=11); pin(f, ff, "D", "L", 25, show=False); pin(f, ff, "Q", "R", 25, show=False)
    z1 = port(f, 480, W["1"][1], "5'd0", 9, w=36)
    z2 = port(f, 730, 400, "5'd0", 9, w=36)
    f.wire([z1["r"], W["1"]])
    f.wire([z2["r"], (780, 400), (780, R["1"][1]), R["1"]])
    f.wire([op1["y"], (500, op1["y"][1]), (500, W["0"][1]), W["0"]], bus="5", seg=0, lpos=0.5, ldy=-2)
    f.wire([W["out"], (640, W["out"][1]), (640, S["1"][1]), S["1"]])
    f.wire([S["out"], (760, S["out"][1]), (760, R["0"][1]), R["0"]])
    f.wire([R["out"], ff["D"]])
    tap = (1090, ff["Q"][1])
    f.wire([ff["Q"], tap], arrow=False); f.dot(tap)
    f.wire([tap, (1090, 262), (660, 262), (660, S["0"][1]), S["0"]], label="hold", seg=1, ldy=-2)
    f.wire([(1090, 262), (1090, 128), (270, 128), (270, op1["a"][1]), op1["a"]], label="sub_q", seg=1, ldy=-2)
    f.dot((1090, 262)); f.dot((270, op1["a"][1]))
    f.wire([(270, op1["a"][1]), (270, op2["a"][1]), op2["a"]])
    f.wire([op2["y"], (470, op2["y"][1]), (470, 420), (578, 420), (578, W["sel"][1])], "ctrl", seg=0)
    f.text(508, 300, "wrap", 10, anchor="start", color="#2e9d3a", halo=True)
    ps = cport(f, 698, 430, "step", 10, "#2e9d3a"); pr = cport(f, 818, 430, "restart", 10, "#2e9d3a")
    f.wire([ps["t"], S["sel"]], "ctrl"); f.wire([pr["t"], R["sel"]], "ctrl")
    o1 = port(f, 1130, ff["Q"][1], "sub_q[4:0]", 10, color="#008a8a")
    f.wire([tap, o1["l"]], "vid")
    # ---- tile counter row
    B2 = 600
    t1 = f.op(300, 540, "tile_q + 1", w=120, h=36, ins=("a",))
    T = f.mux(680, B2, 80, ins=("0", "1"), sel=None, w=36)
    R2 = f.mux(800, B2, 80, ins=("0", "1"), sel=None, w=36)
    ft = f.seq(920, B2 + 15, 130, 50, "tile_q[5:0]", ts=11); pin(f, ft, "D", "L", 25, show=False); pin(f, ft, "Q", "R", 25, show=False)
    z3 = port(f, 730, 700, "6'd0", 9, w=36)
    f.wire([z3["r"], (780, 700), (780, R2["1"][1]), R2["1"]])
    f.wire([T["out"], (760, T["out"][1]), (760, R2["0"][1]), R2["0"]])
    f.wire([R2["out"], ft["D"]])
    tq = (1090, ft["Q"][1])
    f.wire([ft["Q"], tq], arrow=False); f.dot(tq)
    f.wire([tq, (1090, 580), (660, 580), (660, T["0"][1]), T["0"]], label="hold", seg=1, ldy=-2)
    f.wire([(1090, 580), (1090, 520), (270, 520), (270, t1["a"][1]), t1["a"]], label="tile_q", seg=1, ldy=-2)
    f.dot((1090, 580))
    f.wire([t1["y"], (640, t1["y"][1]), (640, T["1"][1]), T["1"]], bus="6", seg=0, lpos=0.5, ldy=-2)
    ag = f.gate("and", 520, 700, 36, 36)
    pst = cport(f, 440, ag["in1"][1], "step", 10, "#2e9d3a"); pwr = cport(f, 440, ag["in2"][1], "wrap", 10, "#2e9d3a")
    f.wire([pst["r"], ag["in1"]], "ctrl"); f.wire([pwr["r"], ag["in2"]], "ctrl")
    f.wire([ag["out"], (698, ag["out"][1]), T["sel"][:1] + (T["sel"][1],)], "ctrl")
    pr2 = cport(f, 818, 740, "restart", 10, "#2e9d3a")
    f.wire([pr2["t"], R2["sel"]], "ctrl")
    o2 = port(f, 1130, ft["Q"][1], "tile_q[5:0]", 10, color="#008a8a")
    f.wire([tq, o2["l"]], "vid")
    f.text(1300, 300, "Why this works:  step and restart arrive in the same clock as x / y change,\nso sub_q / tile_q are exactly aligned with the pixel (no lag).\nsub_q wraps 23 -> 0 and bumps tile_q (tile_q = x / 24 without a divider).\nrestart (end of line / frame) clears both to 0.\ntile_q is 6 bits: the blanking interval counts up to 33 (800 / 24).", 11, anchor="start", color="#333")
    f.text(1300, 450, "Net labels:  'wrap' = output of  sub_q == 23.   'step' / 'restart' are the same net\neverywhere they appear (drawn as labels to avoid long crossing wires).", 10, anchor="start", color="#555")
    f.text(1300, 560, "X-axis instance outputs  ->  col[5:0] = tile_q\nY-axis instance outputs  ->  row[5:0] = tile_q", 12, anchor="start", color="#008a8a", weight="bold")
    partB(f)
    return f


def partB(f):
    f.region(20, 810, 2060, 420, "PART B - in-field test, tile address, RAM fetch (Fig 7 copy V port B) and colour select", "#008a8a")
    pc = port(f, 40, 887, "col[5:0]", 10, color="#008a8a"); pr = port(f, 40, 947, "row[5:0]", 10, color="#008a8a")
    cc = f.op(260, 870, "col < 20", w=110, h=36, ins=("a",)); cr = f.op(260, 930, "row < 20", w=110, h=36, ins=("a",))
    f.wire([pc["r"], cc["a"]]); f.wire([pr["r"], cr["a"]])
    ag = f.gate("and", 480, 900, 36, 36)
    f.wire([cc["y"], (430, 887), (430, ag["in1"][1]), ag["in1"]]); f.wire([cr["y"], (440, 947), (440, ag["in2"][1]), ag["in2"]])
    d = f.seq(570, 893, 120, 50, "in_field_d", ts=11); pin(f, d, "D", "L", 25, show=False); pin(f, d, "Q", "R", 25, show=False)
    f.wire([ag["out"], d["D"]], label="in_field", ldy=-2, lsize=9)
    f.wire([d["Q"], (720, d["Q"][1])], arrow=False, label="in_field_d", ldy=-2, lsize=9)
    f.note(570, 965, "1 FF delay = RAM read latency", 10)
    # tile address
    pr1 = port(f, 40, 1027, "row[5:0]", 10, color="#008a8a"); pr2 = port(f, 40, 1087, "row[5:0]", 10, color="#008a8a")
    s4 = f.op(200, 1010, "row << 4", w=110, h=36, ins=("a",)); s2 = f.op(200, 1070, "row << 2", w=110, h=36, ins=("a",))
    f.wire([pr1["r"], s4["a"]]); f.wire([pr2["r"], s2["a"]])
    a1 = f.op(420, 1040, "+", w=70, h=50, ins=("a", "b"), ts=16); a2 = f.op(580, 1040, "+", w=70, h=50, ins=("a", "b"), ts=16)
    f.wire([s4["y"], (360, s4["y"][1]), (360, a1["a"][1]), a1["a"]]); f.wire([s2["y"], (380, s2["y"][1]), (380, a1["b"][1]), a1["b"]])
    f.wire([a1["y"], (530, a1["y"][1]), (530, a2["a"][1]), a2["a"]])
    pcc = port(f, 440, 1130, "col[5:0]", 10, color="#008a8a")
    f.wire([pcc["r"], (550, 1130), (550, a2["b"][1]), a2["b"]])
    ta = port(f, 730, a2["y"][1], "vga_tile_addr[8:0]  -> Fig 7 copy V, port B", 10, color="#008a8a")
    f.wire([a2["y"], ta["l"]], "vid", bus="9")
    f.text(60, 1190, "tile_addr = row * 20 + col = (row << 4) + (row << 2) + col    (shifts are free wiring; two small adders, no multiplier)", 11, anchor="start", color="#333")
    # colour select
    td = port(f, 1000, 1100, "vga_tile_data[1:0]  (Fig 7)", 10, color="#008a8a")
    cols = [("12'h222 floor", 870), ("12'h888 wall", 910), ("12'hA52 breakable", 950), ("12'h888 (unused)", 990)]
    m4 = f.mux(1300, 850, 160, ins=("0", "1", "2", "3"), sel=None, w=40)
    for i, (t, y) in enumerate(cols):
        p = port(f, 1120, m4[str(i)][1], t, 9, w=120)
        f.wire([p["r"], m4[str(i)]])
    f.wire([td["r"], (1320, 1100), (1320, m4["sel"][1])], "vid", bus="2", seg=0, lpos=0.5, ldy=-2)
    f.dot((1230, 1100)); f.dot((1250, 1100))
    og = f.gate("or", 1380, 1130, 40, 36)
    f.wire([(1230, 1100), (1230, og["in2"][1]), og["in2"]], label="tile[0]", seg=1, ldx=-6, ldy=-14, lsize=9)
    f.wire([(1250, 1100), (1250, og["in1"][1]), og["in1"]], label="tile[1]", seg=1, ldx=22, ldy=-6, lsize=9)
    wa = f.gate("and", 1480, 1130, 36, 36)
    f.wire([og["out"], (1450, og["out"][1]), (1450, wa["in1"][1]), wa["in1"]])
    pf = port(f, 1300, 1195, "in_field_d", 10, color="#008a8a")
    f.wire([pf["r"], (1460, 1195), (1460, wa["in2"][1]), wa["in2"]])
    fm = f.mux(1560, 900, 70, ins=("0", "1"), sel=None, w=40)
    f.wire([m4["out"], (1500, m4["out"][1]), (1500, fm["1"][1]), fm["1"]], bus="12", seg=0, lpos=0.5, ldy=-2)
    pb = port(f, 1420, 880, "12'h000 outside field", 9, w=110)
    f.wire([pb["r"], (1545, 880), (1545, fm["0"][1]), fm["0"]])
    pfs = cport(f, fm["sel"][0], 1010, "in_field_d", 10, "#008a8a")
    f.wire([pfs["t"], fm["sel"]], "vid")
    r1 = f.seq(1660, 910, 140, 50, "maze_rgb_q[11:0]", ts=11); pin(f, r1, "D", "L", 25, show=False); pin(f, r1, "Q", "R", 25, show=False)
    f.wire([fm["out"], r1["D"]], bus="12")
    o = port(f, 1840, r1["Q"][1], "maze_rgb[11:0] -> Fig 10", 10, color="#008a8a")
    f.wire([r1["Q"], o["l"]], "vid", bus="12")
    r2 = f.seq(1660, 1123, 140, 50, "maze_wall_q", ts=11); pin(f, r2, "D", "L", 25, show=False); pin(f, r2, "Q", "R", 25, show=False)
    f.wire([wa["out"], r2["D"]], "vid")
    o3 = port(f, 1840, r2["Q"][1], "maze_wall -> Fig 10", 10, color="#008a8a")
    f.wire([r2["Q"], o3["l"]], "vid")
    f.text(1000, 1230, "wall flag = in_field & (tile != 0)  - same definition as the collision engine (Fig 6b)", 10, anchor="start", color="#555")
