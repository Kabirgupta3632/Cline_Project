from h import *


def build():
    f = Fig(1800, 1100, "Fig 8 - VGA Timing Generator (640 x 480 @ 60 Hz, 25 MHz pixel enable)",
            "Totals: 800 clocks per line (640 visible + 16 front + 96 sync + 48 back), 525 lines per frame (480 visible + 10 front + 2 sync + 33 back).")
    f.region(20, 90, 1760, 400, "HORIZONTAL COUNTER  (advances only when pix_ce = 1)", "#008a8a")
    ce = port(f, 40, 170, "pix_ce", 10, color="#777")
    hm = f.mux(520, 230, 90, ins=("0", "1"), sel="h_end", w=36, top=True)
    hz = port(f, 380, hm["1"][1], "10'd0", 9, w=44)
    f.wire([hz["r"], hm["1"]])
    ha = f.op(280, 220, "hcnt + 1", w=110, h=36, ins=("a",))
    f.wire([ha["y"], (430, ha["y"][1]), (430, hm["0"][1]), hm["0"]], bus="10")
    he = f.mux(660, 230, 90, ins=("0", "1"), sel="pix_ce", w=36, top=True)
    f.wire([hm["out"], he["1"]], bus="10")
    hf = f.seq(800, 245, 110, 50, "hcnt[9:0]", ts=12); pin(f, hf, "D", "L", 25, show=False); pin(f, hf, "Q", "R", 25, show=False)
    f.wire([he["out"], hf["D"]], bus="10")
    tq = (hf["Q"][0] + 40, hf["Q"][1]); f.wire([hf["Q"], tq], arrow=False); f.dot(tq)
    f.wire([tq, (tq[0], 360), (250, 360), (250, ha["a"][1]), ha["a"]], label="hcnt_q", seg=1, ldy=-2)
    f.wire([tq, (tq[0], 130), (700, 130), (700, he["0"][1] - 0), he["0"]], label="hold (pix_ce = 0)", seg=1, ldy=-2) if False else f.wire([(tq[0], 360), (tq[0], 400), (630, 400), (630, he["0"][1]), he["0"]], label="hold", seg=1, ldy=-2)
    f.wire([ce["r"], (680, 170), (680, he["sel"][1] - 0)] if False else [ce["r"], (678, 170), (678, he["sel"][1])], "clk")
    hc = f.op(1000, 220, "hcnt_q == 799", w=160, h=36, ins=("a",), ts=11)
    f.wire([tq, (tq[0], 238), hc["a"]] if False else [(tq[0], tq[1]), (tq[0], hc["a"][1]), hc["a"]])
    he_ = port(f, 1240, hc["y"][1], "h_end", 10, color="#2e9d3a")
    f.wire([hc["y"], he_["l"]], "ctrl")
    f.wire([(1215, hc["y"][1]), (1215, 135), (538, 135), hm["sel"]], "ctrl", label="h_end", seg=1, ldy=-2)
    f.dot((1215, hc["y"][1]), "ctrl")
    f.text(900, 420, "h_end also = line tick for the vertical counter (Part B).", 11, anchor="start", color="#333")
    # ------------------------------------------------ vertical
    f.region(20, 510, 1760, 290, "VERTICAL COUNTER", "#008a8a")
    f.note(240, 530, "advances once per line:  line_tick = pix_ce & h_end", 10)
    p1 = port(f, 40, 585, "pix_ce", 9, color="#777"); p2 = port(f, 40, 635, "h_end", 9, color="#2e9d3a")
    ln = f.gate("and", 130, 595, 40, 40)
    f.wire([p1["r"], (95, 585), (95, ln["in1"][1]), ln["in1"]], "clk")
    f.wire([p2["r"], (105, 635), (105, ln["in2"][1]), ln["in2"]], "ctrl")
    lt = (ln["out"][0] + 30, ln["out"][1])
    f.wire([ln["out"], lt], "ctrl", arrow=False); f.dot(lt, "ctrl")
    f.text(lt[0] + 4, lt[1] - 8, "line_tick", 10, anchor="start", color="#2e9d3a", halo=True)
    va = f.op(300, 540, "vcnt + 1", w=110, h=36, ins=("a",))
    vm = f.mux(480, 590, 90, ins=("0", "1"), sel="v_end", w=36)
    vz = port(f, 380, vm["1"][1], "10'd0", 9, w=44)
    f.wire([vz["r"], vm["1"]])
    f.wire([va["y"], (450, va["y"][1]), (450, vm["0"][1]), vm["0"]], bus="10", seg=0, ldy=-2)
    ve = f.mux(640, 590, 90, ins=("0", "1"), sel="line_tick", w=36)
    f.wire([vm["out"], ve["1"]], bus="10")
    vf = f.seq(780, 605, 110, 50, "vcnt[9:0]", ts=12); pin(f, vf, "D", "L", 25, show=False); pin(f, vf, "Q", "R", 25, show=False)
    f.wire([ve["out"], vf["D"]], bus="10")
    vq = (vf["Q"][0] + 40, vf["Q"][1]); f.wire([vf["Q"], vq], arrow=False); f.dot(vq)
    f.wire([vq, (vq[0], 770), (280, 770), (280, va["a"][1]), va["a"]], label="vcnt_q", seg=1, ldy=-2)
    f.wire([(vq[0], 770), (vq[0], 785), (620, 785), (620, ve["0"][1]), ve["0"]], label="hold", seg=1, ldy=-2) if False else f.wire([(560, 770), (560, 785), (620, 785), (620, ve["0"][1]), ve["0"]], arrow=True)
    f.dot((560, 770))
    f.text(740, 782, "hold (line_tick = 0)", 9, color="#555")
    # line_tick to ve select (route above)
    f.wire([lt, (lt[0], 525), (658, 525), (658, ve["sel"][1] - 0 - 0), ve["sel"]][:0] or [lt, (lt[0], 525), (658, 525), ve["sel"]] if False else [lt, (lt[0], 548), (658, 548), (658, 590 + 90 - 6.3)], "ctrl", arrow=False)
    vc = f.op(960, 600, "vcnt_q == 524", w=160, h=36, ins=("a",), ts=11)
    f.wire([vq, (vq[0], vc["a"][1]), vc["a"]])
    f.wire([vc["y"], (1170, vc["y"][1])], "ctrl", arrow=False)
    vp = (1170, vc["y"][1]); f.dot(vp, "ctrl")
    f.wire([vp, (1170, 560), (498, 560), (498, 590 + 90 - 6.3)], "ctrl", arrow=False)
    vo = port(f, 1210, vp[1], "v_end", 10, color="#2e9d3a")
    f.wire([vp, vo["l"]], "ctrl")
    f.text(1010, 700, "v_end: vcnt wraps to 0 on the last line.  The mux order matters:\nline_tick = 0 -> hold;  line_tick = 1 -> (v_end ? 0 : vcnt + 1).", 10, anchor="start", color="#555")
    # ------------------------------------------------ decode
    f.region(20, 830, 1760, 260, "SYNC / ACTIVE DECODE  (combinational compares + register stage)", "#008a8a")
    items = [("active_c", "hcnt_q < 640  &  vcnt_q < 480", "x = hcnt_q, y = vcnt_q while active"),
             ("hsync_c", "656 <= hcnt_q < 752   (active-low)", "-> hsync_n = ~in_window"),
             ("vsync_c", "490 <= vcnt_q < 492   (active-low)", "-> vsync_n = ~in_window")]
    for i, (nm, rule, note) in enumerate(items):
        y = 880 + i * 70
        c = f.op(60, y, rule, w=360, h=40, ins=("a",), ts=11)
        f.wire([(40, y + 20), c["a"]], bus="20", label="hcnt_q, vcnt_q", ldy=-2) if False else None
        f.text(40, y + 24, "", 1)
        ff = f.seq(520, y - 5, 110, 50, nm.replace("_c", "_q"), ts=11); pin(f, ff, "D", "L", 25, show=False); pin(f, ff, "Q", "R", 25, show=False)
        f.wire([c["y"], ff["D"]], "vid")
        o = port(f, 700, y + 20, nm.replace("_c", "") + "_q", 10, color="#008a8a")
        f.text(700 + o["w"] + 10, y + 24, note, 10, anchor="start", color="#444")
        f.wire([ff["Q"], o["l"]], "vid")
    f.text(1100, 890, "Compare inputs: hcnt_q (Part A) and vcnt_q (Part B).\nOutputs to the rest of the VGA engine\n  x[9:0] = hcnt_q   y[9:0] = vcnt_q\n  active / hsync_n / vsync_n registered once (matches pixel pipeline stage 0)\n\nOne frame = 800 x 525 pixels x 4 clk (100 MHz / 25 MHz) = 1.68 M clk = 16.8 ms = 59.5 Hz.", 11, anchor="start", color="#333")
    return f
