from h import *


def build():
    f = Fig(1900, 1360, "Fig P1 - Pipeline Stage 1 (IF): PC register, instruction NOP muxes, branch-flush shift register",
            "Drawn from the team's IF/ID sketches.  Where a sketch was ambiguous the choice is noted in italics - check it against your RTL.")
    # ============================================================ A  PC
    f.region(20, 90, 1860, 380, "PART A - PC register  (reset mux, stall-hold mux, FF)  ->  inst_fetch_pc_o", "#3b5bdb")
    fp = port(f, 40, 200, "fetch_pc_i[31:0]  (next PC from EX, Fig P5)", 10)
    rs = f.mux(420, 170, 90, ins=("0", "1"), sel="reset", w=40)
    rv = port(f, 300, rs["1"][1], "32'h0  (RESET vector)", 9, w=120)
    f.wire([fp["r"], (400, 200), (400, rs["0"][1]), rs["0"]], bus="32")
    f.wire([rv["r"], rs["1"]])
    hm = f.mux(600, 170, 90, ins=("0", "1"), sel="stall_read_i", w=40)
    f.wire([rs["out"], hm["0"]], bus="32")
    pc = ffq(f, 760, 193, "PC[31:0]", w=130, h=50, ts=12)
    f.wire([hm["out"], pc["D"]], bus="32")
    tq = (pc["Q"][0] + 40, pc["Q"][1]); f.wire([pc["Q"], tq], arrow=False); f.dot(tq)
    f.wire([tq, (tq[0], 330), (570, 330), (570, hm["1"][1]), hm["1"]], bus="32", label="hold (stalled)", seg=1, ldy=-2)
    o = port(f, 1020, pc["Q"][1], "inst_fetch_pc_o[31:0]", 11, color="#3b5bdb")
    f.wire([tq, o["l"]], bus="32")
    f.text(1300, 190, "inst_fetch_pc_o  ->  Instruction Memory address\nand  ->  ID/EX register (pc_ex, Fig P2)", 11, anchor="start", color="#333")
    f.note(60, 400, "reset = 1 -> PC = 0.   stall_read_i = 1 (data-memory read in flight) -> PC holds.   Otherwise PC <= fetch_pc_i = (branch ? target : PC + 4) computed in EX.", 10)
    # ============================================================ B  instruction path
    f.region(20, 500, 1860, 300, "PART B - instruction path:  two NOP-insert muxes (as in the sketch)", "#3b5bdb")
    rd = port(f, 40, 600, "inst_mem_read_data[31:0]", 10, color="#9b3fd6")
    nop1 = port(f, 190, 640, "NOP = 32'h0000_0013", 9, w=130)
    m1 = f.mux(480, 570, 100, ins=("0", "1"), sel="inst_mem_is_valid", w=40)
    f.wire([nop1["r"], (440, 640), (440, m1["0"][1]), m1["0"]]) if False else None
    n1 = port(f, 300, m1["0"][1], "NOP", 9, w=40)
    f.wire([n1["r"], m1["0"]])
    f.wire([rd["r"], (400, 600), (400, m1["1"][1]), m1["1"]], "mem", bus="32")
    m2 = f.mux(700, 570, 100, ins=("0", "1"), sel="stall_read_i", w=40)
    n2 = port(f, 580, m2["0"][1], "NOP", 9, w=40)
    f.wire([n2["r"], m2["0"]])
    f.wire([m1["out"], (640, m1["out"][1]), (640, m2["1"][1]), m2["1"]], bus="32", seg=0, lpos=0.5)
    o2 = port(f, 900, m2["out"][1], "instruction_o[31:0]  -> Fig P2 decode", 11, color="#3b5bdb")
    f.wire([m2["out"], o2["l"]], bus="32")
    f.note(60, 760, "Muxes as in the sketch: input 0 = NOP, input 1 = instruction;  select 1 = inst_mem_is_valid, then stall_read_i.", 10)
    f.note(60, 778, "NOP = addi x0,x0,0 (32'h00000013).  The polarity of the second select (stall_read_i) is read from the sketch - verify it against your RTL.", 10)
    # ============================================================ C  flush shift register
    f.region(20, 830, 1860, 510, "PART C - branch flush shift register  (squash the two instructions fetched behind a taken branch)", "#3b5bdb")
    wb = port(f, 40, 940, "wb_branch_i  (taken branch / jump, from EX)", 10, color="#2e9d3a")
    # stage 1
    zr = f.mux(380, 910, 70, ins=("0", "1"), sel="reset", w=36)
    f.wire([wb["r"], (350, 940), (350, zr["0"][1]), zr["0"]], "ctrl")
    z1 = port(f, 300, zr["1"][1], "0", 9, w=24); f.wire([z1["r"], zr["1"]])
    hm1 = f.mux(520, 910, 70, ins=("0", "1"), sel=None, w=36)
    f.wire([zr["out"], hm1["0"]], "ctrl")
    ff1 = ffq(f, 640, 913, "stall_first", w=120, h=44)
    f.wire([hm1["out"], ff1["D"]], "ctrl")
    t1 = (ff1["Q"][0] + 30, ff1["Q"][1]); f.wire([ff1["Q"], t1], arrow=False); f.dot(t1, "ctrl")
    f.wire([t1, (t1[0], 985), (490, 985), (490, hm1["1"][1]), hm1["1"]], "ctrl", label="hold", seg=1, ldy=-2)
    o1 = port(f, 900, ff1["Q"][1], "wb_stall_first_o", 10, color="#2e9d3a"); f.wire([t1, o1["l"]], "ctrl")
    # stage 2
    zr2 = f.mux(380, 1100, 70, ins=("0", "1"), sel="reset", w=36)
    f.wire([(t1[0], t1[1]), (t1[0], 1070), (350, 1070), (350, zr2["0"][1]), zr2["0"]], "ctrl")
    z2 = port(f, 300, zr2["1"][1], "0", 9, w=24); f.wire([z2["r"], zr2["1"]])
    hm2 = f.mux(520, 1100, 70, ins=("0", "1"), sel=None, w=36)
    f.wire([zr2["out"], hm2["0"]], "ctrl")
    ff2 = ffq(f, 640, 1103, "stall_second", w=120, h=44)
    f.wire([hm2["out"], ff2["D"]], "ctrl")
    t2 = (ff2["Q"][0] + 30, ff2["Q"][1]); f.wire([ff2["Q"], t2], arrow=False); f.dot(t2, "ctrl")
    f.wire([t2, (t2[0], 1190), (490, 1190), (490, hm2["1"][1]), hm2["1"]], "ctrl", label="hold", seg=1, ldy=-2)
    o2_ = port(f, 900, ff2["Q"][1], "wb_stall_second_o", 10, color="#2e9d3a"); f.wire([t2, o2_["l"]], "ctrl")
    f.text(1180, 930, "A taken branch is only known in EX, two instructions later.\nwb_stall_first_o  = 1 for the instruction right behind it,\nwb_stall_second_o = 1 for the one after that.\nBoth are used in WB to suppress their register write and\nmemory write (Fig P9) - same trick as the 2-FF chain in your\nsketch of wb_stall_first_o / wb_stall_second_o.", 11, anchor="start", color="#333")
    # hold-enable logic (from the sketch): ~stall_read_i & (wb_mem_to_reg_i & d_mem_write_valid_i)
    a1 = port(f, 1000, 1215, "wb_mem_to_reg_i", 9, color="#2e9d3a"); a2 = port(f, 1000, 1255, "d_mem_write_valid_i", 9, color="#2e9d3a")
    sr = port(f, 1000, 1180, "stall_read_i", 9, color="#2e9d3a")
    g1 = f.gate("and", 1220, 1225, 36, 36)
    f.wire([a1["r"], (1190, 1215), (1190, g1["in1"][1]), g1["in1"]], "ctrl"); f.wire([a2["r"], (1200, 1255), (1200, g1["in2"][1]), g1["in2"]], "ctrl")
    ng = f.gate("not", 1220, 1166, 30, 28)
    f.wire([sr["r"], (1160, 1170), ng["in"]][:1] + [ng["in"]], "ctrl") if False else f.wire([(sr["r"][0], 1180), ng["in"]], "ctrl")
    g2 = f.gate("and", 1340, 1190, 40, 40)
    f.wire([ng["out"], (1310, ng["out"][1]), (1310, g2["in1"][1]), g2["in1"]], "ctrl")
    f.wire([g1["out"], (1310, g1["out"][1]), (1310, g2["in2"][1]), g2["in2"]], "ctrl")
    he = port(f, 1440, g2["out"][1], "upd_en  (select of both hold muxes)", 10, color="#2e9d3a")
    f.wire([g2["out"], he["l"]], "ctrl")
    f.text(1000, 1150, "Hold-mux select, as drawn in the sketch:", 11, anchor="start", weight="bold")
    f.text(1000, 1300, "upd_en = ~stall_read_i & (wb_mem_to_reg_i & d_mem_write_valid_i)   -> select = 1 loads the new value, 0 holds.\nThe AND-gate inputs are read from the sketch - verify them against your RTL.", 10, anchor="start", color="#555")
    for hmx in (hm1, hm2):
        p = cport(f, hmx["sel"][0], hmx["sel"][1] + 60, "upd_en", 9, "#2e9d3a")
        f.wire([p["t"], hmx["sel"]], "ctrl")
    f.text(1180, 1330, "", 1)
    return f
