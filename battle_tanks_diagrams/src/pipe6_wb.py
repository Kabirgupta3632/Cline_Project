from h import *


def build():
    f = Fig(2000, 1960, "Fig P6 - WB stage: store byte-lane alignment, byte enables, load alignment / sign-extension, result mux",
            "From your 'wb_write_data / wb_write_byte' mux sketch.  SB / SH / SW decide how data and the 4 byte enables are placed in the 32-bit word.")
    part_a(f)
    part_b(f)
    part_c(f)
    return f


def part_a(f):
    f.region(20, 90, 1960, 400, "PART A - store data:  replicate byte / half so it lands in the right lane (select = alu_operation_i[2:0])", "#3b5bdb")
    op2 = port(f, 40, 150, "alu_op2_i[31:0]  (store data)", 10)
    m = f.mux(760, 130, 250, ins=("SB", "SH", "SW", "default"), sel=None, w=60)
    srcs = ["{4{alu_op2_i[7:0]}}", "{2{alu_op2_i[15:0]}}", "alu_op2_i[31:0]", "32'hx"]
    for k, sname in zip(("SB", "SH", "SW", "default"), srcs):
        p = port(f, 420, m[k][1], sname, 9, w=200)
        f.wire([p["r"], m[k]])
    f.wire([op2["r"], (330, 150), (330, 190)], arrow=False)
    f.note(60, 215, "(op2 feeds the three replicate blocks - wiring only)", 10)
    sp = cport(f, m["sel"][0], m["sel"][1] + 50, "alu_operation_i[2:0]", 9, "#2e9d3a")
    f.wire([sp["t"], m["sel"]], "ctrl")
    hz = f.mux(1100, 190, 90, ins=("0", "1"), sel=None, w=40)
    z = port(f, 1020, hz["0"][1], "0", 9, w=24)
    f.wire([z["r"], hz["0"]]); f.wire([m["out"], (1060, m["out"][1]), (1060, hz["1"][1]), hz["1"]], bus="32")
    wsel = cport(f, hz["sel"][0], hz["sel"][1] + 50, "store_en", 9, "#2e9d3a")
    f.wire([wsel["t"], hz["sel"]], "ctrl")
    rs = f.mux(1300, 190, 90, ins=("0", "1"), sel=None, w=40)
    f.wire([hz["out"], rs["0"]], bus="32")
    rz = port(f, 1230, rs["1"][1], "0", 9, w=24); f.wire([rz["r"], rs["1"]])
    rsel = cport(f, rs["sel"][0], rs["sel"][1] + 50, "reset", 9, "#2e9d3a")
    f.wire([rsel["t"], rs["sel"]], "ctrl")
    o = port(f, 1450, rs["out"][1], "wb_write_data_o[31:0]  -> data memory", 11, color="#3b5bdb")
    f.wire([rs["out"], o["l"]], bus="32")
    # store_en
    a = port(f, 40, 380, "stall_read_i", 9, color="#2e9d3a"); b = port(f, 40, 430, "mem_write_i", 9, color="#2e9d3a")
    n = f.gate("not", 200, 366, 30, 28)
    f.wire([a["r"], n["in"]], "ctrl")
    g = f.gate("and", 330, 395, 40, 40)
    f.wire([n["out"], (300, n["out"][1]), (300, g["in1"][1]), g["in1"]], "ctrl"); f.wire([b["r"], (310, 430), (310, g["in2"][1]), g["in2"]], "ctrl")
    se = port(f, 450, g["out"][1], "store_en = ~stall_read_i & mem_write_i", 10, color="#2e9d3a")
    f.wire([g["out"], se["l"]], "ctrl")
    f.text(900, 400, "store_en is the select of the 'store gating' mux (and of the byte-enable mux in Part B);\nonly a real, non-stalled store may drive data/enables.", 10, anchor="start", color="#555")


def part_b(f):
    f.region(20, 520, 1960, 560, "PART B - byte enables (wb_write_byte_o[3:0]):  by width and by address bits [1:0]", "#3b5bdb")
    ad = port(f, 40, 600, "write_address_i[1:0]", 10)
    sb = f.mux(540, 580, 200, ins=("2'b00", "2'b01", "2'b10", "2'b11"), sel=None, w=50)
    for k, v in zip(("2'b00", "2'b01", "2'b10", "2'b11"), ("4'b0001", "4'b0010", "4'b0100", "4'b1000")):
        p = port(f, 400, sb[k][1], v, 9, w=70)
        f.wire([p["r"], sb[k]])
    f.wire([ad["r"], (300, 600)], arrow=False)
    sp = cport(f, sb["sel"][0], sb["sel"][1] + 45, "write_address_i[1:0]", 9, "#2e9d3a"); f.wire([sp["t"], sb["sel"]], "ctrl")
    hm = f.mux(540, 860, 80, ins=("0", "1"), sel=None, w=50)
    h0 = port(f, 400, hm["0"][1], "4'b0011", 9, w=70); h1 = port(f, 400, hm["1"][1], "4'b1100", 9, w=70)
    f.wire([h0["r"], hm["0"]]); f.wire([h1["r"], hm["1"]])
    sh = cport(f, hm["sel"][0], hm["sel"][1] + 45, "write_address_i[1]", 9, "#2e9d3a"); f.wire([sh["t"], hm["sel"]], "ctrl")
    wm = f.mux(860, 700, 240, ins=("SB", "SH", "SW", "default"), sel=None, w=60)
    f.wire([sb["out"], (810, sb["out"][1]), (810, wm["SB"][1]), wm["SB"]], bus="4")
    f.wire([hm["out"], (830, hm["out"][1]), (830, wm["SH"][1]), wm["SH"]], bus="4")
    sw = port(f, 760, wm["SW"][1], "4'b1111", 9, w=70); f.wire([sw["r"], wm["SW"]])
    dx = port(f, 760, wm["default"][1], "4'bx", 9, w=50); f.wire([dx["r"], wm["default"]])
    wsp = cport(f, wm["sel"][0], wm["sel"][1] + 50, "alu_operation_i[2:0]", 9, "#2e9d3a"); f.wire([wsp["t"], wm["sel"]], "ctrl")
    g2 = f.mux(1060, 760, 90, ins=("0", "1"), sel=None, w=40)
    z = port(f, 980, g2["0"][1], "4'b0", 9, w=44); f.wire([z["r"], g2["0"]])
    f.wire([wm["out"], (1010, wm["out"][1]), (1010, g2["1"][1]), g2["1"]], bus="4")
    se = cport(f, g2["sel"][0], g2["sel"][1] + 50, "store_en", 9, "#2e9d3a"); f.wire([se["t"], g2["sel"]], "ctrl")
    r = f.mux(1220, 760, 90, ins=("0", "1"), sel=None, w=40)
    f.wire([g2["out"], r["0"]], bus="4")
    rz = port(f, 1140, r["1"][1], "4'b0", 9, w=44); f.wire([rz["r"], r["1"]])
    rp = cport(f, r["sel"][0], r["sel"][1] + 50, "reset", 9, "#2e9d3a"); f.wire([rp["t"], r["sel"]], "ctrl")
    o = port(f, 1380, r["out"][1], "wb_write_byte_o[3:0]  -> data memory", 11, color="#3b5bdb")
    f.wire([r["out"], o["l"]], bus="4")
    w2 = port(f, 1380, 640, "wb_write_address_o[31:0] = ex_result  (word address)", 10, color="#3b5bdb")
    f.text(1400, 1000, "write enables for SB: one-hot by address [1:0];\nSH: low pair if addr[1]=0, high pair if addr[1]=1;\nSW: all four.", 10, anchor="start", color="#555")


def part_c(f):
    f.region(20, 1110, 1960, 820, "PART C - load path: pick the byte / half from the read word, sign- or zero-extend, then write-back result mux", "#3b5bdb")
    rd = port(f, 40, 1190, "wb_read_data[31:0]  (from Fig 2b)", 10, color="#1f6fe0")
    lm = f.mux(560, 1170, 100, ins=("0", "1", "2", "3"), sel=None, w=50)
    for i in range(4):
        p = port(f, 330, lm[str(i)][1], "rd[%d:%d]" % (8 * i + 7, 8 * i), 9, w=70)
        f.wire([p["r"], lm[str(i)]])
    f.wire([rd["r"], (300, 1190)], arrow=False)
    la = cport(f, lm["sel"][0], lm["sel"][1] + 45, "wb_addr[1:0]", 9, "#2e9d3a"); f.wire([la["t"], lm["sel"]], "ctrl")
    bx = f.op(780, 1190, "sign-extend 8->32", w=170, h=40, ins=("a",), ts=10)
    f.wire([lm["out"], (720, lm["out"][1]), (720, bx["a"][1]), bx["a"]], bus="8")
    hm = f.mux(560, 1380, 80, ins=("0", "1"), sel=None, w=50)
    for i in range(2):
        p = port(f, 330, hm[str(i)][1], "rd[%d:%d]" % (16 * i + 15, 16 * i), 9, w=70)
        f.wire([p["r"], hm[str(i)]])
    hp = cport(f, hm["sel"][0], hm["sel"][1] + 45, "wb_addr[1]", 9, "#2e9d3a"); f.wire([hp["t"], hm["sel"]], "ctrl")
    hx = f.op(780, 1400, "sign-extend 16->32", w=170, h=40, ins=("a",), ts=10)
    f.wire([hm["out"], hx["a"]], bus="16")
    f.wire([(300, 1190), (300, 1190)], arrow=False, width=0.1)
    om = f.mux(1150, 1260, 280, ins=("LB", "LBU", "LH", "LHU", "LW", "-"), sel=None, w=60)
    ub = f.op(780, 1260, "zero-extend 8", w=170, h=36, ins=("a",), ts=10)
    f.wire([(720, 1190), (720, ub["a"][1]), ub["a"]]); f.dot((720, 1190))
    f.wire([(690, 1420), (690, uh["a"][1]), uh["a"]]) if False else None
    f.wire([bx["y"], (1050, bx["y"][1]), (1050, om["LB"][1]), om["LB"]], bus="32")
    f.wire([ub["y"], (1060, ub["y"][1]), (1060, om["LBU"][1]), om["LBU"]], bus="32")
    f.wire([hx["y"], (1070, hx["y"][1]), (1070, om["LH"][1]), om["LH"]], bus="32")
    uh2 = f.op(780, 1470, "zero-extend 16", w=170, h=36, ins=("a",), ts=10)
    f.wire([hm["out"], (700, hm["out"][1]), (700, uh2["a"][1]), uh2["a"]]); f.dot((700, hm["out"][1]))
    f.wire([uh2["y"], (1080, uh2["y"][1]), (1080, om["LHU"][1]), om["LHU"]], bus="32")
    zz = port(f, 960, om["-"][1], "32'hx", 9, w=50); f.wire([zz["r"], om["-"]])
    lw = port(f, 960, om["LW"][1] + 30, "rd[31:0]  (word)", 9, w=110)
    f.wire([lw["r"], (1100, lw["r"][1]), (1100, om["LW"][1]), om["LW"]])
    lsp = cport(f, om["sel"][0], om["sel"][1] + 50, "load_type = alu_operation_i[2:0]", 9, "#2e9d3a"); f.wire([lsp["t"], om["sel"]], "ctrl")
    ld = port(f, 1300, om["out"][1], "load_result[31:0]", 10, color="#3b5bdb")
    f.wire([om["out"], ld["l"]], bus="32")
    # result mux
    rm = f.mux(1560, 1330, 100, ins=("0 ex_result", "1 load_result"), sel=None, w=50)
    e = port(f, 1480, rm["0 ex_result"][1] - 0, "ex_result_wb", 9, w=80)
    f.wire([e["r"], rm["0 ex_result"]])
    f.wire([ld["r"], (1520, ld["r"][1]), (1520, rm["1 load_result"][1]), rm["1 load_result"]], bus="32")
    mp = cport(f, rm["sel"][0], rm["sel"][1] + 50, "wb_mem_to_reg", 9, "#2e9d3a"); f.wire([mp["t"], rm["sel"]], "ctrl")
    ro = port(f, 1660, rm["out"][1], "wb_result[31:0]", 11, color="#d62828")
    f.text(1660, rm["out"][1] + 30, "-> regfile + forwarding (Fig P4)", 10, anchor="start", color="#555")
    f.wire([rm["out"], ro["l"]], "fwd", bus="32")
    f.text(1000, 1650, "Only loads use the read data; every other instruction writes ex_result.\nSquashed instructions (wb_stall_first / second, Fig P1) have reg write-enable forced to 0 here.", 10, anchor="start", color="#555")
    sq = port(f, 1000, 1770, "wb_write_en = reg_write & ~wb_stall_first & ~wb_stall_second", 10, color="#d62828")
