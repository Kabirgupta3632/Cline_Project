from h import *


def reduce_or(f, x, y, names, out, color="#008a8a"):
    n = len(names)
    h = 18 * n + 10
    g = f.gate("or", x, y, 46, h)
    for i, nm in enumerate(names):
        yy = y + 6 + (h - 12) * (i + 0.5) / n
        f.text(x - 8, yy + 3, nm, 9, anchor="end", color="#333")
        f.wire([(x - 4, yy), (x + 6, yy)], arrow=False, width=1.2)
    o = port(f, x + 90, y + h / 2, out, 10, color=color)
    f.wire([g["out"], o["l"]], "vid")
    return o


def build():
    f = Fig(1900, 1640, "Fig 9 - Sprite Engine: Per-Pixel Tank and Bullet Hit Test (x, y from the VGA timing generator)",
            "offset = (x - sprite_x, y - sprite_y).  Unsigned subtract makes 'negative' offsets huge, so ONE compare (offset < size) tests both edges.\n"
            "If inside the box, a small ROM gives the shape bit (1 clk latency, so the in-box flag is delayed 1 FF).")
    # ============================================================ A  tank cell
    f.region(20, 90, 1860, 570, "PART A - tank cell  (instantiate 2x:  T = P1 / P2)", "#008a8a")
    rom = f.mem(600, 440, 340, 190, "Tank Sprite ROM", sub="16 angles x 20 x 20 x 1 bit\nsync read: shape bit 1 clk later",
                L=("ang[3:0]", "dy[4:0]", "dx[4:0]"), R=("shape",), pad=112)
    px = port(f, 40, 150, "x[9:0]  (Fig 8)", 10, color="#008a8a")
    tx = port(f, 40, 200, "tank_x[9:0]  (Fig 5)", 10, color="#a35c00")
    py = port(f, 40, 320, "y[9:0]  (Fig 8)", 10, color="#008a8a")
    ty = port(f, 40, 370, "tank_y[9:0]  (Fig 5)", 10, color="#a35c00")
    an = port(f, 40, rom["ang[3:0]"][1], "ang_T[3:0]  (Fig 5)", 10, color="#a35c00")
    sx = f.op(320, 150, "x - tank_x", w=130, h=56, ins=("a", "b"), ts=11)
    sy = f.op(320, 320, "y - tank_y", w=130, h=56, ins=("a", "b"), ts=11)
    f.wire([px["r"], (280, 150), (280, sx["a"][1]), sx["a"]])
    f.wire([tx["r"], (300, 200), (300, sx["b"][1]), sx["b"]])
    f.wire([py["r"], (280, 320), (280, sy["a"][1]), sy["a"]])
    f.wire([ty["r"], (300, 370), (300, sy["b"][1]), sy["b"]])
    DX, DY = 490, 520
    f.wire([sx["y"], (DX, sx["y"][1])], arrow=False, label="dx[9:0]", ldy=-2); f.dot((DX, sx["y"][1]))
    f.wire([sy["y"], (DY, sy["y"][1])], arrow=False, label="dy[9:0]", ldy=-2); f.dot((DY, sy["y"][1]))
    cx = f.op(600, 150, "dx < 20", w=110, h=40, ins=("a",), ts=11)
    cy = f.op(600, 320, "dy < 20", w=110, h=40, ins=("a",), ts=11)
    f.wire([(DX, sx["y"][1]), (DX, cx["a"][1]), cx["a"]])
    f.wire([(DY, sy["y"][1]), (DY, cy["a"][1]), cy["a"]])
    f.wire([(DX, sx["y"][1]), (DX, rom["dx[4:0]"][1]), rom["dx[4:0]"]], bus="5", label="dx[4:0]", seg=1, lpos=0.55, ldx=6, ldy=0) if False else f.wire([(DX, sx["y"][1]), (DX, rom["dx[4:0]"][1]), rom["dx[4:0]"]], bus="5", seg=1, lpos=0.5, ldy=-2)
    f.wire([(DY, sy["y"][1]), (DY, rom["dy[4:0]"][1]), rom["dy[4:0]"]], bus="5", seg=1, lpos=0.5, ldy=-2)
    f.wire([an["r"], rom["ang[3:0]"]], "reg", bus="4")
    ag = f.gate("and", 780, 245, 40, 40)
    f.wire([cx["y"], (750, cx["y"][1]), (750, ag["in1"][1]), ag["in1"]])
    f.wire([cy["y"], (750, cy["y"][1]), (750, ag["in2"][1]), ag["in2"]])
    d1 = f.seq(900, 245, 110, 44, "in_box_d", ts=10); pin(f, d1, "D", "L", 22, show=False); pin(f, d1, "Q", "R", 22, show=False)
    f.wire([ag["out"], d1["D"]], label="in_box", ldy=-2, lsize=9)
    a2 = f.gate("and", 1130, 330, 40, 40)
    f.wire([d1["Q"], (1090, d1["Q"][1]), (1090, a2["in1"][1]), a2["in1"]])
    f.wire([rom["shape"], (1050, rom["shape"][1]), (1050, a2["in2"][1]), a2["in2"]], label="shape", seg=0, ldy=-2)
    tv = port(f, 1300, a2["out"][1], "tank_valid_T", 10, color="#008a8a")
    f.wire([a2["out"], tv["l"]], "vid")
    cc = port(f, 1300, 450, "tank_rgb_T[11:0] = constant", 10, color="#008a8a")
    f.text(1300, 485, "P1: 12'h0F0 (green)    P2: 12'h00F (blue)   - fixed per instance", 10, anchor="start", color="#444")
    f.text(1100, 585, "Both tanks run in parallel; the two {rgb, valid} pairs are combined in Part C.", 11, anchor="start", color="#333")
    # ============================================================ B  bullet cell
    f.region(20, 690, 1860, 520, "PART B - bullet cell  (instantiate 8x:  N = 0..7)", "#008a8a")
    bx = port(f, 40, 750, "x[9:0]", 10, color="#008a8a"); bbx = port(f, 40, 800, "bN_x[9:0]  (Fig 5)", 10, color="#a35c00")
    by = port(f, 40, 880, "y[9:0]", 10, color="#008a8a"); bby = port(f, 40, 930, "bN_y[9:0]  (Fig 5)", 10, color="#a35c00")
    sxb = f.op(280, 750, "x - bN_x", w=120, h=56, ins=("a", "b"), ts=11)
    syb = f.op(280, 880, "y - bN_y", w=120, h=56, ins=("a", "b"), ts=11)
    f.wire([bx["r"], (230, 750), (230, sxb["a"][1]), sxb["a"]]); f.wire([bbx["r"], (250, 800), (250, sxb["b"][1]), sxb["b"]])
    f.wire([by["r"], (230, 880), (230, syb["a"][1]), syb["a"]]); f.wire([bby["r"], (250, 930), (250, syb["b"][1]), syb["b"]])
    # size mux
    bg = port(f, 40, 1100, "bN_big  (Fig 5)", 10, color="#a35c00")
    sz = f.mux(300, 1020, 70, ins=("0", "1"), sel=None, w=36)
    z6 = port(f, 210, sz["0"][1], "5'd6", 9, w=36); z12 = port(f, 210, sz["1"][1], "5'd12", 9, w=40)
    f.wire([z6["r"], sz["0"]]); f.wire([z12["r"], sz["1"]])
    f.wire([bg["r"], (318, 1100), (318, 1020 + 70 - 5)], "reg")
    cbx = f.op(560, 735, "dx < size", w=120, h=56, ins=("a", "b"), ts=11)
    cby = f.op(560, 865, "dy < size", w=120, h=56, ins=("a", "b"), ts=11)
    rom2 = f.mem(560, 1000, 340, 190, "Bullet Sprite ROM", sub="disc 6x6 / disc 12x12\nsync read: shape bit 1 clk later",
                 L=("big", "dy[3:0]", "dx[3:0]"), R=("shape",), pad=112)
    DX, DY, SZ = 430, 460, 520
    f.wire([sxb["y"], (DX, sxb["y"][1])], arrow=False, label="dx", ldy=-2); f.dot((DX, sxb["y"][1]))
    f.wire([syb["y"], (DY, syb["y"][1])], arrow=False, label="dy", ldy=-2); f.dot((DY, syb["y"][1]))
    f.wire([(DX, sxb["y"][1]), (DX, cbx["a"][1]), cbx["a"]])
    f.wire([(DY, syb["y"][1]), (DY, cby["a"][1]), cby["a"]])
    f.wire([(DX, sxb["y"][1]), (DX, rom2["dx[3:0]"][1]), rom2["dx[3:0]"]], bus="4", seg=1, lpos=0.5, ldy=-2)
    f.wire([(DY, syb["y"][1]), (DY, rom2["dy[3:0]"][1]), rom2["dy[3:0]"]], bus="4", seg=1, lpos=0.5, ldy=-2)
    f.wire([sz["out"], (SZ, sz["out"][1]), (SZ, cby["b"][1]), cby["b"]], bus="5", label="size", seg=0, ldy=-2); f.dot((SZ, sz["out"][1]))
    f.wire([(SZ, sz["out"][1]), (SZ, cbx["b"][1]), cbx["b"]]) if False else f.wire([(SZ, cby["b"][1]), (SZ, cbx["b"][1]), cbx["b"]]); f.dot((SZ, cby["b"][1]))
    f.wire([(318, 1100), (500, 1100), (500, rom2["big"][1]), rom2["big"]], "reg"); f.dot((318, 1100), "reg")
    g1 = f.gate("and", 760, 800, 40, 50)
    f.wire([cbx["y"], (730, cbx["y"][1]), (730, g1["in1"][1]), g1["in1"]])
    f.wire([cby["y"], (740, cby["y"][1]), (740, g1["in2"][1]), g1["in2"]])
    d2 = f.seq(880, 800, 110, 44, "in_box_d", ts=10); pin(f, d2, "D", "L", 22, show=False); pin(f, d2, "Q", "R", 22, show=False)
    f.wire([g1["out"], d2["D"]])
    g2 = f.gate("and", 1100, 880, 40, 40)
    f.wire([d2["Q"], (1050, d2["Q"][1]), (1050, g2["in1"][1]), g2["in1"]])
    f.wire([rom2["shape"], (1030, rom2["shape"][1]), (1030, g2["in2"][1]), g2["in2"]], label="shape", seg=0, ldy=-2)
    ba = port(f, 905, 1060, "bN_act  (Fig 5)", 10, color="#a35c00")
    d3 = f.seq(1120, 1040, 100, 40, "act_d", ts=10); pin(f, d3, "D", "L", 20, show=False); pin(f, d3, "Q", "R", 20, show=False)
    f.wire([ba["r"], d3["D"]], "reg")
    g3 = f.gate("and", 1280, 910, 40, 40)
    f.wire([g2["out"], (1200, g2["out"][1]), (1200, g3["in1"][1]), g3["in1"]])
    f.wire([d3["Q"], (1260, d3["Q"][1]), (1260, g3["in2"][1]), g3["in2"]])
    hit = (g3["out"][0] + 30, g3["out"][1]); f.wire([g3["out"], hit], arrow=False, label="bN_in", ldy=-2); f.dot(hit)
    ni = f.gate("not", 1400, 790, 30, 26)
    ia = f.gate("and", 1480, 830, 40, 36); ib = f.gate("and", 1480, 960, 40, 36)
    bq = port(f, 1380, 700, "bN_big", 9, color="#a35c00")
    f.wire([hit, (hit[0], 798), ni["in"]][:1] + [(hit[0], ia["in1"][1]), ia["in1"]], arrow=True)
    f.wire([hit, (hit[0], ib["in1"][1]), ib["in1"]]) if False else f.wire([(hit[0], ia["in1"][1]), (hit[0], ib["in1"][1]), ib["in1"]])
    f.wire([bq["b"], (bq["b"][0], 803), (bq["b"][0], 803)], arrow=False, width=0.1)
    f.wire([(bq["r"][0], 700), (1450, 700), (1450, ni["out"][1] - 40), ][:0] + [(bq["b"][0], bq["b"][1]), (bq["b"][0], 803), ni["in"]], "reg", arrow=True)
    f.wire([ni["out"], (1455, ni["out"][1]), (1455, ia["in2"][1]), ia["in2"]])
    f.wire([(bq["b"][0], 803), (bq["b"][0], ib["in2"][1]), ib["in2"]], "reg"); f.dot((bq["b"][0], 803), "reg")
    o1 = port(f, 1620, ia["out"][1], "bN_small_hit", 10, color="#008a8a"); o2 = port(f, 1620, ib["out"][1], "bN_big_hit", 10, color="#008a8a")
    f.wire([ia["out"], o1["l"]], "vid"); f.wire([ib["out"], o2["l"]], "vid")
    f.text(1000, 1170, "Bullet cell latency = 1 clk (ROM / FF), same as the tank cell.  Colours: small = 12'hFF0 yellow, big = 12'hF00 red (constants in the mixer).", 10, anchor="start", color="#444")
    # ============================================================ C  combine
    f.region(20, 1240, 1860, 380, "PART C - combine the 8 bullets and the 2 tanks into the three pixel streams for the mixer (Fig 10)", "#008a8a")
    reduce_or(f, 170, 1300, ["b%d_small_hit" % i for i in range(8)], "bullet_valid")
    reduce_or(f, 560, 1300, ["b%d_big_hit" % i for i in range(8)], "big_valid")
    tp = f.mux(1000, 1330, 90, ins=("0", "1"), sel="tank_valid_P2", w=40, top=True)
    t1 = port(f, 790, tp["0"][1], "tank_rgb_P1", 9); t2 = port(f, 790, tp["1"][1], "tank_rgb_P2", 9)
    f.wire([t1["r"], tp["0"]]); f.wire([t2["r"], tp["1"]])
    sp = port(f, 1000, 1280, "tank_valid_P2", 9, color="#008a8a")
    f.wire([(sp["b"][0] + 0, sp["b"][1]), (1020, 1320)][:0] + [(1020, sp["b"][1]), tp["sel"]], "ctrl")
    tv = f.gate("or", 1000, 1470, 40, 36)
    a = port(f, 790, tv["in1"][1], "tank_valid_P1", 9); b = port(f, 790, tv["in2"][1], "tank_valid_P2", 9)
    f.wire([a["r"], tv["in1"]]); f.wire([b["r"], tv["in2"]])
    o3 = port(f, 1180, tp["out"][1], "tank_rgb[11:0]", 10, color="#008a8a")
    f.wire([tp["out"], o3["l"]], "vid", bus="12")
    o4 = port(f, 1180, tv["out"][1], "tank_valid", 10, color="#008a8a")
    f.wire([tv["out"], o4["l"]], "vid")
    f.text(1400, 1400, "Tank overlap (rare): P2 wins via the select mux.\nAll three outputs are registered once (not drawn)\nso the mixer sees stable inputs.", 11, anchor="start", color="#333")
    f.text(100, 1560, "Outputs -> Fig 10 mixer:  tank_rgb/tank_valid,  bullet_valid (yellow),  big_valid (red).", 11, anchor="start", color="#2e9d3a", weight="bold")
    return f
