from h import *


def build():
    f = Fig(2100, 1500, "Fig 6b - Collision Engine (1/3): Bullet-Wall Scan  (one shared maze-RAM lookup, 8 bullets in 8 clocks)",
            "A scan counter time-shares ONE maze-RAM read port across the 8 bullet slots.  tile_addr is registered and BRAM read takes 1 clk, so scan index and act are delayed 2 clocks to match.")
    f.region(20, 90, 2060, 1380, "WALL SCAN DATAPATH", "#8a6d00")
    # scan counter
    sc = f.seq(60, 175, 110, 50, "scan[2:0]", ts=12); pin(f, sc, "D", "L", 25, show=False); pin(f, sc, "Q", "R", 25, show=False)
    ad = f.op(60, 262, "scan + 1", w=110, h=36, ins=("a",))
    tq = (sc["Q"][0] + 30, sc["Q"][1]); f.wire([sc["Q"], tq], arrow=False, bus="3", label="scan_q", ldy=-2); f.dot(tq)
    f.wire([tq, (tq[0], ad["a"][1]), (ad["a"][0] - 20, ad["a"][1]), ad["a"]][:0] or [tq, (tq[0], 243), ad["y"]], arrow=False) if False else None
    f.wire([tq, (tq[0], 325), (30, 325), (30, ad["a"][1]), ad["a"]])
    f.wire([ad["y"], (200 + 0, ad["y"][1])], arrow=False)
    f.wire([(200, ad["y"][1]), (200, 150), (40, 150), (40, sc["D"][1]), sc["D"]], bus="3", seg=1, ldy=-2, lpos=0.5)
    f.dot((200, ad["y"][1]))
    f.note(260, 215, "free-running 0..7;  scan_q = bullet index being tested", 10)
    f.text(1000, 140, "Every box labelled scan_q[2:0] is the SAME net (output of the scan counter): it selects all four 8:1 muxes\nand feeds the delay register at the right.  Boxes labelled bN_* are the Fig 5 register outputs.", 11, anchor="start", color="#2e9d3a")
    # four 8:1 muxes
    mx = mux8(f, 300, 340, "bN_x[9:0]")
    my = mux8(f, 300, 600, "bN_y[9:0]")
    mb = mux8(f, 300, 860, "bN_big", bus="8")
    ma = mux8(f, 300, 1120, "bN_act", bus="8")
    # centre offset: half = big ? 6 : 3
    hm = f.mux(470, 862, 70, ins=("0", "1"), sel="big", w=36, top=True)
    c3 = port(f, 400, hm["0"][1], "4'd3", 9, w=36); c6 = port(f, 400, hm["1"][1], "4'd6", 9, w=36)
    f.wire([c3["r"], hm["0"]]); f.wire([c6["r"], hm["1"]])
    f.wire([mb["out"], (520, mb["out"][1]), (520, 840), (488, 840), hm["sel"]][:2] + [(520, 835), (488, 835), (488, hm["sel"][1] - 0)], "ctrl", arrow=False)
    f.note(470, 960, "half-size: normal 6x6 -> 3, big 12x12 -> 6", 10)
    # centre adders
    ax = f.op(640, 380, "cx = x + half", w=150, h=40, ins=("a", "b"), ts=11)
    ay = f.op(640, 640, "cy = y + half", w=150, h=40, ins=("a", "b"), ts=11)
    f.wire([mx["out"], (580, mx["out"][1]), (580, ax["a"][1]), ax["a"]], bus="10", seg=0, lpos=0.5)
    f.wire([my["out"], (580, my["out"][1]), (580, ay["a"][1]), ay["a"]], bus="10", seg=0, lpos=0.5)
    hx = (hm["out"][0] + 20, hm["out"][1])
    f.wire([hm["out"], hx], arrow=False); f.dot(hx)
    f.wire([hx, (hx[0], 520), (610, 520), (610, ax["b"][1]), ax["b"]], bus="4", seg=1, ldy=-2)
    f.wire([hx, (hx[0], 740), (610, 740), (610, ay["b"][1]), ay["b"]], bus="4", seg=1, ldy=-2)
    # divide-by-24 (multiply-shift) blocks
    dx = f.comb(860, 370, 190, 60, "col = (cx * 683) >> 14", ts=11, sub="= cx / 24  (exact for cx < 480)", showpins=False)
    dy = f.comb(860, 630, 190, 60, "row = (cy * 683) >> 14", ts=11, sub="= cy / 24  (exact for cy < 480)", showpins=False)
    f.wire([ax["y"], (dx["x"], ax["y"][1])] if False else [ax["y"], (860, ax["y"][1])], bus="10", label="cx")
    f.wire([ay["y"], (860, ay["y"][1])], bus="10", label="cy")
    dx.p["in"] = (860, ax["y"][1]); dy.p["in"] = (860, ay["y"][1])
    dx.p["out"] = (1050, 400); dy.p["out"] = (1050, 660)
    # tile address
    sh = f.comb(1160, 430, 270, 130, "tile_addr = row*20 + col", ts=12, sub="= (row << 4) + (row << 2) + col\nshift-add only, no multiplier\n(9 bits: 0..399)", showpins=False)
    f.wire([dx["out"], (1100, 400), (1100, 470), (1160, 470)], bus="5", label="col", seg=2, ldy=-2)
    f.wire([dy["out"], (1100, 660), (1100, 520), (1160, 520)], bus="5", label="row", seg=2, ldy=12)
    # ---- address register (timing) + maze RAM port C
    ar = f.seq(1440, 455, 120, 50, "addr_q[8:0]", ts=11); pin(f, ar, "D", "L", 25, show=False); pin(f, ar, "Q", "R", 25, show=False)
    f.wire([(1430, 480), ar["D"]], bus="9", label="", seg=0)
    mr = f.mem(1620, 420, 210, 130, "Maze RAM  Port C", sub="read-only copy (Fig 7)\nsync read: data 1 clk\nafter addr", L=("addr",), R=("data",), pad=100, showpins=False)
    f.wire([ar["Q"], (1620, 480)], "mem", bus="9", label="to RAM")
    f.text(1650, 540, "tile = 2 bits", 10, anchor="start", color="#555")
    dp = (1830, 480)
    f.wire([(1830, 480), (1860, 480)], "mem", arrow=False); f.dot((1860, 480), "mem")
    orr = f.gate("or", 1900, 470, 40, 36)
    f.wire([(1860, 480), (1860, 478), orr["in1"]][:1] + [(1860, orr["in1"][1]), orr["in1"]], "mem", label="tile[1]", seg=0, ldx=-6, ldy=-4)
    f.wire([(1860, 480), (1860, orr["in2"][1]), orr["in2"]], "mem", label="tile[0]", seg=1, ldx=-6, ldy=14)
    f.note(1620, 575, "tile code: 0 floor   1 wall   2 breakable wall   3 unused\nwall = tile[1] | tile[0]  (any non-floor stops/reflects a bullet)", 10)
    # ---- 2-clk delay of scan index and act (addr_q + BRAM latency)
    sd = f.seq(1380, 700, 150, 50, "scan_d[2:0] (2 FF)", ts=10); pin(f, sd, "D", "L", 25, show=False); pin(f, sd, "Q", "R", 25, show=False)
    ad2 = f.seq(1380, 800, 150, 50, "act_d (2 FF)", ts=10); pin(f, ad2, "D", "L", 25, show=False); pin(f, ad2, "Q", "R", 25, show=False)
    p1 = port(f, 1210, 725, "scan_q[2:0]", 9, color="#2e9d3a")
    f.wire([p1["r"], sd["D"]], "ctrl", bus="3")
    f.wire([ma["out"], (340 + 20, ma["out"][1]), (1300, ma["out"][1]), (1300, ad2["D"][1]), ad2["D"]], "reg", label="act (selected)", seg=1, lpos=0.5, ldy=-2)
    f.note(1380, 1060, "2 FFs each: tile_addr register + BRAM read latency,\nso scan_d / act_d line up with the tile data", 10)
    wa = f.gate("and", 1700, 770, 40, 40)
    f.wire([orr["out"], (1990, orr["out"][1]), (1990, 660), (1660, 660), (1660, wa["in1"][1]), wa["in1"]], label="wall", seg=1, ldy=-2)
    f.wire([ad2["Q"], (1640, ad2["Q"][1]), (1640, wa["in2"][1]), wa["in2"]])
    dc = f.comb(1380, 920, 200, 120, "3-to-8 Decoder", sub="one-hot of scan_d", showpins=False)
    f.wire([sd["Q"], (1560, sd["Q"][1]), (1560, 760), (1340, 760), (1340, 980), (1380, 980)], bus="3", label="scan_d", seg=2, ldy=-2, ldx=-30)
    g8 = f.gate("and", 1720, 960, 44, 40)
    f.wire([(1580, 980), (1680, 980), (1680, g8["in2"][1]), g8["in2"]] if False else [(1580, 990), (1690, 990), (1690, g8["in2"][1]), g8["in2"]], bus="8", label="onehot", seg=0, lpos=0.4, ldy=-2)
    f.wire([wa["out"], (1790, wa["out"][1]), (1790, 900), (1660, 900), (1660, g8["in1"][1]), g8["in1"]][:0] or [wa["out"], (1780, wa["out"][1]), (1780, 910), (1670, 910), (1670, g8["in1"][1]), g8["in1"]], label="wall_hit_now", seg=2, ldy=-2)
    wo = port(f, 1830, g8["out"][1], "wall_set[7:0]", 11, color="#2e9d3a")
    f.wire([g8["out"], wo["l"]], "ctrl", bus="8")
    f.text(1000, 1300, "wall_set[i] = wall_hit_now & (scan_d == i)   (8 bit-sliced AND gates)\n-> sets sticky WALL_HIT_MASK[i] in Fig 6d.   Sweep = 8 clocks (+2 latency) = 200 ns @ 50 MHz,\nfar below one 16.7 ms video frame, so every bullet is checked many times per frame.\nThe test point is the bullet CENTRE; bounce/lifetime logic itself runs in C.", 11, anchor="start", color="#333")
    return f
